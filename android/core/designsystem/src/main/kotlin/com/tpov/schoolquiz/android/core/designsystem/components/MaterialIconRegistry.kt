/** Case-insensitive lookup of [materialIconRegistry]. */
private val materialIconRegistryByLowercase: Map<String, ImageVector> =
    materialIconRegistry.entries.associate { (k, v) -> k.lowercase() to v }

/** Resolve an icon name to a Material Icon. Returns null when the name is not whitelisted. */
fun materialIconByName(name: String?): ImageVector? {
    if (name.isNullOrBlank()) return null
    return materialIconRegistryByLowercase[name.trim().lowercase()]
}

/**
 * Resolve a list of icon names to a list of Material Icons. Names that are not in the
 * whitelist are silently skipped — caller decides what to do with the (possibly empty)
 * result.
 */
fun resolveIcons(names: List<String>): List<ImageVector> =
    names.mapNotNull(::materialIconByName)
