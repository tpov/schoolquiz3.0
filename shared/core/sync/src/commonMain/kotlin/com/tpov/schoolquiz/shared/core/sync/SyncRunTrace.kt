package com.tpov.schoolquiz.shared.core.sync

import com.tpov.schoolquiz.shared.core.network.SyncError
import kotlinx.coroutines.flow.Flow

/**
 * Какой прогон оставил след.
 *
 * Прогонов больше одного, и они независимы: эпик 9 развёл содержимое и профиль по разным
 * расписаниям намеренно — квесты играются офлайн, поэтому серверная копия профиля может отставать,
 * ничем на экране не соврав. Раз расписания разные, то и «когда последний раз прошло» у них разное:
 * один след на два прогона означал, что удачный профильный прогон снимает ветвь упавшего
 * контентного и ставит поверх неё свежее время успеха — игрок видит «синхронизировались минуту
 * назад» при содержимом, которое не приезжало сутки.
 *
 * Сводить их в одно число нельзя (AD-14) по той же причине, по какой нельзя складывать состояния
 * очереди: минимум двух времён — это «содержимое устарело», названное словом «профиль», а максимум
 * — прямая ложь про то, что не приехало.
 */
enum class SyncRunKind {
    /** Содержимое: очередь, каталоги, приватные квесты, задания ревью, таблица экономики. */
    CONTENT,

    /** Собственное состояние аккаунта: профиль и то, что от него зависит. Каденция реже. */
    PROFILE,

    /**
     * «Перечитать всё» (AD-30) — ручное перечитывание журналов с начала.
     *
     * След свой, потому что читающая сторона у него другая: ресинк не отправляет очередь и не
     * трогает профиль. Записать его успех в контентный след значило бы объявить прошедшим прогон,
     * половина которого даже не запускалась, — и снять ветвь ошибки, которая не починилась.
     */
    RESYNC,
}

/**
 * След прогона: когда синхронизация последний раз прошла целиком и чем кончилась последняя неудача.
 *
 * След принадлежит владельцу и виду прогона, а не сеансу. «Синхронизировались 20 минут назад» —
 * факт про аккаунт, и перезапуск процесса его не отменяет: пока след жил в памяти, каждый холодный
 * старт показывал игроку «синхронизации ещё не было», хотя очередь была пуста именно потому, что
 * она уехала.
 *
 * @property lastSuccessAtMs время удачного прогона из инжектированного источника. Ноль — ни разу.
 * @property lastError ветвь последней неудачи. Ветвь, а не текст исключения (AD-15).
 */
data class SyncRunTrace(
    val lastSuccessAtMs: Long = 0L,
    val lastError: SyncError? = null,
)

/**
 * Порт следа прогона: хранит его по владельцу и виду прогона и переживает перезапуск процесса.
 *
 * Ключ — пара `owner_uid` + вид прогона. Владелец в ключе, потому что инвариант 8 запрещает
 * показывать следующему игроку числа предыдущего: чтение по чужому ключу не находит ничего и
 * отдаёт нули, а не чужое время. Вид прогона в ключе, потому что расписаний несколько и общая
 * строка означала бы, что последний доложивший затирает исход соседа. Удаление следов прежнего
 * владельца — вторая операция AD-8, и она забирает все его строки, сколько бы видов ни было.
 *
 * Времени здесь не берут: его приносит вызывающий из единственного источника (AD-9).
 */
interface SyncRunTraceStore {
    /**
     * Следы этого владельца по видам прогона — все разом, одной подпиской.
     *
     * Вид, о котором записи нет, в карте отсутствует и читается как [SyncRunTrace] по умолчанию —
     * нули, а не пустой поток (инвариант 8, NFR8): пустой поток оставил бы подписчика без единого
     * значения, и он показал бы прошлое.
     */
    fun observeTraces(ownerUid: String): Flow<Map<SyncRunKind, SyncRunTrace>>

    /** Удачный проход: время записывается, прошлая ошибка этого же вида снимается — она починилась. */
    suspend fun recordSuccess(
        ownerUid: String,
        kind: SyncRunKind,
        atMs: Long,
    )

    /** Неудача: пишется ветвь, а время последнего успеха этого вида остаётся прежним. */
    suspend fun recordFailure(
        ownerUid: String,
        kind: SyncRunKind,
        error: SyncError,
    )
}

/** След названного вида — или нули, если прогон этого вида ещё не оставлял следа. */
fun Map<SyncRunKind, SyncRunTrace>.traceOf(kind: SyncRunKind): SyncRunTrace = this[kind] ?: SyncRunTrace()
