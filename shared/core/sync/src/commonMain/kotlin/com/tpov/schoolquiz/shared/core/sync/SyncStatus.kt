package com.tpov.schoolquiz.shared.core.sync

import com.tpov.schoolquiz.shared.core.network.SyncError
import com.tpov.schoolquiz.shared.core.outbox.OutboxCounts
import kotlinx.coroutines.flow.Flow

/**
 * Что игрок может узнать про синхронизацию.
 *
 * Сегодня наружу не выходит ничего, кроме `Log.w`: приложение не сообщает ни что четыре действия
 * ждут отправки, ни что одно из них уже никогда не уедет. Узнать это нельзя никак.
 *
 * Числа раздельные намеренно (AD-14). Одно «ожидает» на все состояния скрыло бы и конфликт, и
 * карантин — а это ровно те два случая, где игроку нужно что-то сделать. Поля-суммы над
 * состояниями здесь запрещены критерием и стережутся `SyncStatusModelGuardTest`.
 *
 * Времена и ветви тоже раздельные, и по той же причине. Расписаний несколько (AD-14, эпик 9):
 * содержимое, профиль и ручное «Перечитать всё». Пока след у них был общий, удачный профильный
 * прогон снимал ветвь упавшего контентного и ставил свежее время успеха — игрок видел
 * «синхронизировались минуту назад» при содержимом, которое не приезжало сутки. Свести их в одно
 * число нельзя: минимум — это «содержимое устарело», названное словом «профиль», а максимум —
 * прямая ложь про то, что не приехало.
 *
 * Пара без приставки — контентный прогон: именно от него зависит свежесть того, что игрок видит на
 * экране, и именно её показывают шторка и настройки.
 *
 * @property lastSuccessAtMs когда содержимое последний раз приехало целиком. Ноль — ни разу.
 * @property counts сколько записей в каком состоянии.
 * @property lastError чем кончился последний неудачный контентный прогон, если он был.
 * @property profileLastSuccessAtMs когда профиль последний раз приехал целиком. Ноль — ни разу.
 * @property profileLastError чем кончился последний неудачный профильный прогон.
 * @property resyncLastSuccessAtMs когда «Перечитать всё» последний раз прошло. Ноль — ни разу.
 * @property resyncLastError чем кончилось последнее неудачное «Перечитать всё».
 * @property unreadableChanges сколько записей журналов последние проходы не смогли прочесть —
 *   сумма по всем четырём, у каждого своё слагаемое от его последнего прохода.
 */
data class SyncStatus(
    val lastSuccessAtMs: Long = 0L,
    val counts: OutboxCounts = OutboxCounts(),
    val lastError: SyncError? = null,
    val unreadableChanges: Int = 0,
    val profileLastSuccessAtMs: Long = 0L,
    val profileLastError: SyncError? = null,
    val resyncLastSuccessAtMs: Long = 0L,
    val resyncLastError: SyncError? = null,
) {
    /** Приезжало ли содержимое хоть раз. Отличается от «приехало только что». */
    val hasEverSucceeded: Boolean get() = lastSuccessAtMs > 0L

    /** Приезжал ли профиль хоть раз. Своё время — своё «ещё не было» (AD-14). */
    val hasProfileEverSucceeded: Boolean get() = profileLastSuccessAtMs > 0L

    /** Проходило ли «Перечитать всё» хоть раз. Отдельный ответ на отдельное действие игрока. */
    val hasResyncEverSucceeded: Boolean get() = resyncLastSuccessAtMs > 0L

    /**
     * Были ли записи журнала, которых читатель не понял.
     *
     * Красным не помечается: игроку тут делать нечего — ни повтор, ни «Перечитать всё» не помогут,
     * запись останется такой же непонятной. Сказать всё равно надо: содержимое устарело, и молчать
     * об этом значит показывать старое как свежее.
     */
    val hasUnreadableChanges: Boolean get() = unreadableChanges > 0
}

/**
 * Состояние синхронизации наружу.
 *
 * Auth-scoped по инварианту 8: поток пересоздаётся при смене аккаунта, потому что и очередь, и
 * её счётчики принадлежат конкретному `uid` (AD-8). Пустой поток для отсутствующего аккаунта
 * запрещён — гость видит нули, а не отсутствие данных.
 */
interface SyncStatusRepository {
    fun observeStatus(): Flow<SyncStatus>

    /**
     * Отмечает удачный проход названного вида.
     *
     * Вид обязателен и умолчания не имеет: забыть его — значит вернуть общий след, в котором
     * удачный профильный прогон снимал ветвь упавшего контентного.
     */
    suspend fun recordSuccess(
        kind: SyncRunKind,
        atMs: Long,
    )

    /** Отмечает неудачу названного вида — с типом, а не с текстом (AD-15). */
    suspend fun recordFailure(
        kind: SyncRunKind,
        error: SyncError,
        atMs: Long,
    )

    /**
     * Сколько записей журнала проход не смог прочесть.
     *
     * Журнал называется явно, потому что журналов четыре и все они сообщают в одно число. Без
     * имени последний доложивший затирал бы остальных: три журнала показывали бы ноль, будучи
     * полны непонятых записей, и «backfill закончен» следовало бы из чужого нуля (AD-11).
     *
     * Внутри одного журнала — замещает, а не накапливает: число описывает его последний проход.
     * Наружу выходит сумма по всем четырём.
     *
     * @param journal имя журнала из [SyncJournals].
     */
    suspend fun recordUnreadableChanges(
        journal: String,
        count: Int,
    )
}

/**
 * Имена четырёх журналов — те же, что у их курсоров.
 *
 * Нужны, чтобы счёт непонятых записей из разных журналов не затирал друг друга: каждый кладёт
 * своё число под своим именем, а игрок видит сумму.
 */
object SyncJournals {
    /** Журналы каталогов: `catalogs/{id}/sync_changes`, все вместе за один проход. */
    const val CATALOGS: String = "catalogs"

    /** Журнал содержимого урока: `lesson_content/{id}/sync_changes`. */
    const val LESSON_CONTENT: String = "lesson_content"

    /** Журнал приватных квестов автора: `private/{uid}/sync_changes`. */
    const val PRIVATE_QUESTS: String = "private_quests"
}
