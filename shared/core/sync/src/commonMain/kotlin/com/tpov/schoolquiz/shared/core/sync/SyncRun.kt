package com.tpov.schoolquiz.shared.core.sync

import com.tpov.schoolquiz.shared.core.network.SyncError
import com.tpov.schoolquiz.shared.core.network.syncErrorOrNull

/**
 * Один прогон синхронизации: все шаги подряд и ровно один след на весь прогон.
 *
 * До этого следа не было ни у одного прогона воркера: исход уходил в `Log.w`, и «нет сети» при
 * чтении каталога, приватных квестов, заданий ревью или профиля не доходило до экрана вообще —
 * молчание синхронизации было неотличимо от её успеха (AD-14).
 *
 * Успех — свойство прогона, а не шага. Пока успех записывал сам шаг, любой удавшийся шаг стирал
 * ветвь ошибки соседа по тому же прогону: очередь уезжала, каталог падал, и игрок видел свежее
 * время последней удачной синхронизации при устаревшем содержимом. Поэтому запись здесь одна и
 * она последняя: успех — только когда весь прогон прошёл целиком, иначе ветвь первой неудачи.
 *
 * Первой, а не последней: при отсутствии сети первым падает тот шаг, который первым пошёл к
 * серверу, и его ветвь и есть причина. Последняя неудача в такой цепочке — то же самое, но
 * названное шагом, который к причине отношения не имеет.
 *
 * Из первых берётся первая **названная**. Ветвь есть не у каждого шага: источник, который ещё не
 * пропущен через разбор ошибок, отдаёт голое исключение, и оно приезжает безымянным. Пока
 * записывалась просто первая, один такой шаг в начале списка прятал за «неизвестно» настоящую
 * причину, названную следующим, — а порядок шагов задаёт композиционный корень, и игрок видел
 * причину или не видел в зависимости от того, вошёл ли он в аккаунт. Безымянная неудача
 * записывается только тогда, когда названной во всём прогоне не было.
 *
 * **Прогон — не один.** Расписаний несколько (эпик 9), и каждое пишет под своим [SyncRunKind]:
 * иначе удачный профильный прогон снимал бы ветвь упавшего контентного, ставя поверх неё своё
 * время, — и «синхронизировались минуту назад» стояло бы над содержимым суточной давности. Вид
 * приходит параметром, а не полем: писатель исхода один на всё приложение, а расписаний много, и
 * второй экземпляр здесь означал бы второго владельца решения об исходе.
 *
 * Ветвь берётся из [SyncFailure] через [syncErrorOrNull] — типом, а не разбором текста (AD-15).
 * Про фичи здесь не знают: прогон видит список [Syncable] и ничего больше (AD-7).
 */
class SyncRun(
    private val status: SyncStatusRepository,
    private val clock: () -> Long,
) {
    /**
     * Прогоняет все шаги по порядку и записывает исход прогона под его видом.
     *
     * Неудача одного шага не отменяет остальные — они независимы, и выход по первой же неудаче
     * означал бы, что каталог, стоящий в списке после отказавшего профиля, не приедет никогда.
     *
     * @param kind какое расписание это было. Свой след у каждого — сводить их нельзя (AD-14).
     * @param steps шаги в том порядке, в каком их назвал композиционный корень.
     * @param onStepFailure куда сообщить про отдельный упавший шаг: журнал остаётся у платформы,
     *   ядру он не нужен.
     * @return успех, если прогон прошёл целиком, иначе первая неудача — та самая, что записана
     *   в след. Результат, а не признак: вызывающий, которому исход нужно вернуть игроку (ручное
     *   «Перечитать всё»), иначе снова принимал бы решение об исходе сам.
     */
    suspend fun run(
        kind: SyncRunKind,
        steps: List<Syncable>,
        onStepFailure: (Syncable, Throwable) -> Unit = { _, _ -> },
    ): Result<Unit> {
        var firstFailure: Throwable? = null
        var firstNamedFailure: Throwable? = null
        for (step in steps) {
            step.sync().onFailure { error ->
                onStepFailure(step, error)
                if (firstFailure == null) firstFailure = error
                if (firstNamedFailure == null && error.syncErrorOrNull() != null) firstNamedFailure = error
            }
        }
        val failure = firstNamedFailure ?: firstFailure
        return if (failure == null) {
            status.recordSuccess(kind, clock())
            Result.success(Unit)
        } else {
            status.recordFailure(kind, failure.syncErrorOrNull() ?: SyncError.Unknown(failure), clock())
            // Наружу — первая неудача по порядку: она оборвала прогон раньше всех, и вызывающий
            // отвечает за прогон, а не за то, какая из причин названа лучше.
            Result.failure(firstFailure ?: failure)
        }
    }
}
