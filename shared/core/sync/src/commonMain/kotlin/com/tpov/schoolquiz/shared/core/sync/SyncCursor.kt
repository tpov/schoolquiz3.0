package com.tpov.schoolquiz.shared.core.sync

/**
 * Место, на котором остановилось чтение журнала изменений.
 *
 * Пара, а не одно время (AD-31). Строгое сравнение по одному `changedAtMs` теряет записи,
 * записанные в одну миллисекунду: две сущности, изменённые одним пакетом, получают один
 * таймстемп, курсор встаёт на него, и вторая уже никогда не будет прочитана. Второй половиной
 * идёт id документа — он уникален, поэтому пара упорядочивает журнал строго.
 *
 * Сравнение лексикографическое: сначала время, при равенстве — id.
 *
 * Пустой [docId] — «в этой миллисекунде ещё ничего не прочитано»: так выглядит курсор, доставшийся
 * от прежней схемы, хранившей одно число. По лексикографическому сравнению это граница не позже
 * прежней, поэтому читатель перечитает миллисекунду целиком, а не перескочит её.
 */
data class SyncCursor(
    val changedAtMs: Long,
    val docId: String = "",
) : Comparable<SyncCursor> {
    init {
        require(changedAtMs >= 0) { "changedAtMs must be non-negative" }
    }

    override fun compareTo(other: SyncCursor): Int {
        val byTime = changedAtMs.compareTo(other.changedAtMs)
        return if (byTime != 0) byTime else docId.compareTo(other.docId)
    }

    companion object {
        /** Начало журнала: читать всё. Оно же — результат принудительного сброса (AD-30). */
        val BEGINNING = SyncCursor(changedAtMs = 0L, docId = "")
    }
}

/**
 * Одна страница журнала.
 *
 * Читать журнал целиком нельзя: полная перепубликация большого курса приходит одним ответом, и
 * его размер ограничен только тем, сколько успел изменить автор.
 *
 * @property changes прочитанное и разобранное, в порядке курсора.
 * @property nextCursor куда встать после успешного применения. Пусто, если страница пустая.
 *   Двигается по последнему ПРОЧИТАННОМУ документу, а не по последней разобранной записи: иначе
 *   битая запись в конце страницы читалась бы вечно.
 * @property hasMore есть ли ещё — страница пришла полной, значит стоит зайти снова.
 * @property unreadable сколько записей на этой странице читатель не понял и пропустил.
 */
data class SyncChangePage<T>(
    val changes: List<T>,
    val nextCursor: SyncCursor?,
    val hasMore: Boolean,
    /**
     * Пропущенные записи журнала.
     *
     * В журналах сосуществуют три формы документа, и читатель терпит их все, а непонятую запись
     * отбрасывает (AD-11). Терпимость снимается только после того, как backfill приведёт
     * записанное к одной форме, — но узнать, что он закончил, было не из чего: пропуск не
     * оставлял следа. Это число и есть след.
     *
     * Для игрока это значит, что об изменении узла ему сказали, а прочитать его не смогли: узел
     * остался прежним, и «Синхронизировать» этого не исправит.
     */
    val unreadable: Int = 0,
) {
    companion object {
        /** Журнал кончился. */
        fun <T> empty(): SyncChangePage<T> = SyncChangePage(emptyList(), null, hasMore = false)
    }
}

/** Сколько записей журнала читаем за раз. */
const val SYNC_PAGE_SIZE: Int = 200

/**
 * Собирает страницу из прочитанных документов журнала.
 *
 * Один помощник на все четыре читателя: страница, курсор и счёт непонятого считаются одинаково,
 * иначе у каждого журнала была бы своя версия правила.
 *
 * Курсор страницы — максимум по прочитанным документам, включая те, которые разобрать не удалось:
 * иначе битая запись в конце страницы читалась бы вечно. Максимум, а не последний: порядок
 * гарантирует запрос, но фейк в тесте — нет, и курсор, вставший ниже уже прочитанного, отдал бы
 * те же записи снова.
 *
 * Полная страница означает «скорее всего есть ещё»: журнал мог кончиться ровно на границе, и
 * лишний пустой заход дешевле пропущенной записи.
 *
 * @param documents прочитанное, как есть.
 * @param limit размер страницы, с которым делался запрос.
 * @param cursorOf пара документа — время и его id.
 * @param parse разбор документа; `null` — запись непонятна и идёт в [SyncChangePage.unreadable].
 */
fun <D, T> journalPage(
    documents: List<D>,
    limit: Int,
    cursorOf: (D) -> SyncCursor,
    parse: (D) -> T?,
): SyncChangePage<T> {
    if (documents.isEmpty()) return SyncChangePage.empty()
    val changes = documents.mapNotNull(parse)
    return SyncChangePage(
        changes = changes,
        nextCursor = documents.maxOf(cursorOf),
        hasMore = documents.size >= limit,
        unreadable = documents.size - changes.size,
    )
}
