package com.tpov.schoolquiz.shared.core.sync

/**
 * Насколько строго читатель разбирает журналы — один переключатель на все четыре (AD-11, AD-13).
 *
 * В журналах сосуществуют старые формы записи, и читатель их терпит: `quest`/`quests`, каталог с
 * квестом в теле вместо id документа, id задания вместо id документа журнала. Терпимость нужна,
 * пока backfill не привёл записанное к одной форме, — но снимать её было нечем: у терпимости не
 * было ни имени, ни выключателя, и «после backfill» ничем не отличалось от «до».
 *
 * Теперь отличается. [TOLERANT] — до backfill: старые формы разбираются, непонятая запись
 * считается и курсор её проходит. [STRICT] — после: старые формы больше не разбираются, а
 * непонятая запись останавливает проход отказом, курсор остаётся на месте, и следующий проход
 * читает ту же страницу заново. Молчаливого «изменений нет» не остаётся ни в одном из двух
 * режимов: в первом есть число, во втором — отказ.
 *
 * Переключатель один и живёт в composition root. Два означали бы, что журнал ревью можно сделать
 * строгим, забыв про журнал урока, — и одна половина клиента ослепла бы (AD-13).
 */
class JournalReadPolicy(
    /** Останавливать ли проход на непонятой записи вместо того, чтобы её посчитать. */
    val strict: Boolean,
) {
    companion object {
        /** До backfill: терпим старые формы, пропуск оставляет след числом. */
        val TOLERANT: JournalReadPolicy = JournalReadPolicy(strict = false)

        /** После backfill: старых форм больше нет, и встреченная непонятая запись — отказ. */
        val STRICT: JournalReadPolicy = JournalReadPolicy(strict = true)
    }
}

/**
 * Непонятая запись в строгом режиме.
 *
 * Не `IllegalStateException`: прогон обязан отличать «журнал не приведён» от любой другой поломки,
 * иначе снятие терпимости выглядит как отказ сети.
 *
 * @property cursorId журнал, на котором проход встал.
 * @property count сколько записей страницы читатель не понял.
 */
class UnreadableJournalEntriesException(
    val cursorId: String,
    val count: Int,
) : Exception(
        "журнал $cursorId: $count непонятых записей, курсор оставлен на месте — страница будет перечитана",
    )
