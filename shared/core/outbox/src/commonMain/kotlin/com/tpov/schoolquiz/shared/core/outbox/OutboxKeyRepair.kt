package com.tpov.schoolquiz.shared.core.outbox

/**
 * Переписывание ключей у недоехавших записей одной операции — механика без знания о телах (AD-7).
 *
 * Ключ идемпотентности выводится из идентификаторов действия (AD-2). Пока вывод меняется,
 * записанные прежней формой ряды остаются честным намерением с ключом, которого сервер ждёт
 * иначе: такой ряд отказывает по чужому (общему между аккаунтами) ключу и после попыток
 * карантинится молча — ретро эпика 8, находка 4 (голоса `polls.SUBMIT_VOTE` до поправки §2
 * `402c5882`). Лечится переписыванием ключа по новому выводу, и вывод этот знает только
 * владеющая фича: ядро в тело записи не смотрит, поэтому правило приходит сюда аргументом.
 *
 * Границы механики, одинаковые для всех операций:
 * - трогаются только ожидающие записи (`WAITING`, `WAITING_PRECONDITION`): подтверждённых в
 *   очереди нет (очередь — не архив, AD-4), а карантин и конфликт для переписывания не
 *   вскрываются — ряд, уже отказавший по старой форме, остаётся разобранным последствием
 *   (AD-28), и не ему возвращать потерянную попытку;
 * - `null` от правила — строка остаётся как есть (например, она уже новой формы);
 * - занятый целевой ключ пропускается, а не роняет проход: уникальный индекс `mutation_id`
 *   держит «один ключ — одно действие» (AD-2), и падение на нём остановило бы всю очередь.
 *
 * Ответственность за смысл лежит на правиле: новый ключ обязан быть выводом того же намерения,
 * а не заменой действия (AD-2). Серверная защита от двойного применения — идемпотентность
 * приёмника и серверная уникальность сущности — остаётся последней линией, как и для любого
 * повтора.
 */
interface OutboxKeyRepair {
    /** Сколько записей получили новый ключ. */
    suspend fun rewritePendingKeys(
        operation: String,
        repair: (ownerUid: String, mutationId: String) -> String?,
    ): Int
}
