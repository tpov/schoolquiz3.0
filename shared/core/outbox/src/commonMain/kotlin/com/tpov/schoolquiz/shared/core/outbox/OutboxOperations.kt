package com.tpov.schoolquiz.shared.core.outbox

/**
 * Имена отложимых операций.
 *
 * Строка, а не enum: одна таблица на все типы действий (AD-5) тем и держится, что ядро в тип не
 * смотрит. Но имя — часть контракта с сервером: незнакомую операцию приёмник отвергает
 * окончательно, поэтому обе стороны обязаны писать её одинаково. Здесь эти имена и объявлены,
 * чтобы клиент не придумывал их по месту.
 *
 * Список пополняется вместе с реестром `MUTATION_HANDLERS` в `functions/index.js`.
 */
object OutboxOperations {
    /**
     * Разблокировка урока за нолики. Пространство имён владеющей фичи — `lesson` (NFR4).
     *
     * Откладывается по AD-3: цену считает сервер из времени самого урока, а не из состояния,
     * которого у клиента нет, и повтор безопасен по набору уже купленного.
     *
     * Имя было голым — `UNLOCK_LESSON`, единственное в этом списке без пространства имён фичи.
     * Голое имя NFR4 нарушает не формально: правило требует, чтобы `operation` и `entity_ref`
     * жили в одном пространстве, а [OutboxNamespace.of] у имени без разделителя возвращает имя
     * целиком — то есть ссылка `lesson.LESSON:<id>` к такой операции подойти не может вовсе, и
     * писателю пришлось бы либо выдумывать ссылку в пространстве `UNLOCK_LESSON`, либо обходиться
     * без неё, оставив карточку урока без пометки.
     */
    const val UNLOCK_LESSON: String = "lesson.UNLOCK"

    /** Прохождение урока. Пространство имён владеющей фичи. */
    const val SUBMIT_ATTEMPT: String = "lesson_runner.SUBMIT_ATTEMPT"

    /** Online-created box opening; retries resolve the same permanent server operation. */
    const val OPEN_GIFT_BOX: String = "economy.OPEN_GIFT_BOX"

    /**
     * Квитанция готовности онлайн-перехода next-question (ONLINE-O2 §4, история 2.6 эпика
     * `epic-ordinary-delivery`).
     *
     * Пер-вопросная квитанция перехода, а не терминальный расчёт: ответы идут по существующим
     * каналам режима, ready-ACK их не подменяет и не дублирует. Имя операции и кодирование тройки
     * `(attemptId, questionIndex, windowId)` в sourceId фиксирует контракт; кодирование живёт во
     * владеющей фиче (`lesson-runner:data`), серверная половина — реестр `MUTATION_HANDLERS`
     * (`functions/index.js`), совпадение имён сторожит `OutboxOperationsRegistryTest`.
     */
    const val READY_ACK: String = "lesson_runner.READY_ACK"

    /**
     * Shared by lifetime policy, transport classification and Room's parameterized queries.
     *
     * READY_ACK входит сюда по правилу retry контракта (ONLINE-O2 §6.1): готовый ready-ACK живёт
     * только внутри активной попытки, его правило — «повтор возвращает то же», без
     * возрастного карантина и лимита попыток — перезревание убило бы вопрос раньше его
     * собственного deadline, прямое нарушение §7. Решение о включении и имя операции — истории 2.6.
     * SUBMIT_POLL_VOTE — по правилу §4 контракта UX-O7 (история 8.2): тот же мотив.
     */
    val permanentReceiptOperations: Set<String> = setOf(SUBMIT_ATTEMPT, OPEN_GIFT_BOX, READY_ACK, SUBMIT_POLL_VOTE)

    /**
     * Операции, чья мутация ведётся по согласию игрока с платными условиями (CAP-16, AD-5).
     *
     * Клиентский двойник реестра `MUTATION_TERMS_OPERATIONS` в `functions/index.js`: транспорт
     * прикладывает к конверту `capturedTerms` — захваченный снимок платных условий, — а сервер
     * сверяет его с текущей таблицей и отвергает операцию с пометкой `terms-consent-required`,
     * если согласие устарело. Совпадение двух реестров сторожит
     * `OutboxOperationsRegistryTest`: расхождение — это либо отправка согласия, которое сервер
     * не читает, либо платная операция без согласия, которую сервер отвергнет окончательно.
     *
     * Критерий совпадает с серверным и живёт там же, в реестре: цена попытки берётся из
     * согласованной таблицы, потолок заряда применяется при расчёте. `lesson.UNLOCK` не входит:
     * он платится из выделенного уроку времени, а не из таблицы.
     */
    val termsConsentOperations: Set<String> = setOf(SUBMIT_ATTEMPT)

    /** Оценка квеста, поставленная после урока. */
    const val SUBMIT_RATING: String = "lesson_runner.SUBMIT_RATING"

    /** Заявка черновика на арену. */
    const val SUBMIT_ARENA: String = "quest_authoring.SUBMIT_ARENA"

    /**
     * Снятие своего лота с продажи — имени и логотипа.
     *
     * Откладывается по AD-3: результат выводится из ключа лота, и только из него; покупка того
     * же лота, наоборот, синхронна. Лот, ушедший другому, пока запись ждала, — окончательный отказ.
     */
    const val CANCEL_NICKNAME_LISTING: String = "profile.CANCEL_NICKNAME_LISTING"
    const val CANCEL_LOGO_LISTING: String = "profile.CANCEL_LOGO_LISTING"

    /**
     * Решение ревьюера по заданию. Локальной половины нет: запись ревью и репутацию пишет только
     * сервер (AD-25), в очередь кладётся одно намерение.
     */
    const val SUBMIT_REVIEW: String = "quest_authoring.SUBMIT_REVIEW"

    /**
     * Перенос публичного квеста на другую полку. Локальной половины нет: полка серверно-защищена
     * (AD-25), в очередь кладётся одно намерение, а новая полка приезжает журналом.
     */
    const val SET_SHELF: String = "quest.SET_SHELF"

    /**
     * Приватный отчёт об ошибке урока — общий inbox (AD-20, история 4.9 эпика authoring-review).
     *
     * Откладывается по AD-3: тело — текст про весь урок и его id, адресата (разрешённого автора)
     * сервер выводит из документа размещения сам. Повтор по ключу не создаёт второй отчёт.
     * Имя в пространстве владеющей фичи `lesson_report`; серверная половина — реестр
     * `MUTATION_HANDLERS` (`functions/index.js`), совпадение сторожит `OutboxOperationsRegistryTest`.
     */
    const val SUBMIT_LESSON_ERROR: String = "lesson_report.SUBMIT_ERROR"

    /**
     * Голос опроса (UX-O7 §2/§4, история 8.2 эпика `epic-social-features`).
     *
     * Тело — один замороженный набор `selectedOptionIds` (AD-28), ключ выводится из тройки
     * серия/revision/вопрос (`sourceId = "series-<id>-r<rev>-q<idx>"`), entity_ref — серия
     * (`polls.SERIES:<id>`). Входит в [permanentReceiptOperations] по правилу §4: принятый
     * голос живёт «повтор возвращает то же» без возрастного карантина — состаривание в карантин
     * открыло бы участнику второй голос после карантина, прямое нарушение §3. В
     * [termsConsentOperations] голос не входит: опросы не платные.
     */
    const val SUBMIT_POLL_VOTE: String = "polls.SUBMIT_VOTE"

    /**
     * Публикация серии опросов единым draft (UX-O7 §6.2, история 8.2).
     *
     * Откладывается по AD-3: всё содержание серии едет в теле, эффекта вне его нет. Ключ
     * выводится из серии и ожидаемой следующей revision — то же намерение даёт тот же ключ,
     * переиздание того же содержания сервер отвечает no-op без новой revision.
     */
    const val PUBLISH_POLL_SERIES: String = "polls.PUBLISH_SERIES"

    /**
     * Ключ идемпотентности, выведенный из идентификатора самого действия.
     *
     * Ключ рождается вместе с намерением игрока и не меняется ни при одной попытке (AD-2).
     * Выводить его из уже существующего идентификатора — не экономия, а требование: повторная
     * постановка того же намерения (переигранная транзакция, повторный прогон миграции 5 → 6)
     * обязана дать ту же строку, иначе одно действие уедет на сервер дважды под разными ключами.
     *
     * Точка из [operation] заменяется дефисом: сервер принимает ключ только из `[A-Za-z0-9_-]`.
     * Ровно этот же вывод делает миграция 5 → 6 в SQL — разъедутся, и перенесённая запись
     * встанет в очередь второй раз.
     */
    fun mutationKey(
        operation: String,
        sourceId: String,
    ): String {
        require(sourceId.isNotBlank()) { "sourceId must not be blank" }
        return operation.replace('.', '-') + "-" + sourceId
    }

    /**
     * Ключ мутации, которой игрок разрешает конфликт, — выведенный из прежнего ключа и версии,
     * поверх которой он согласился отправить заново.
     *
     * Ключ обязан быть новым: изменённая ожидаемая версия — это другая мутация, и прежний ключ
     * сервер уже видел (AD-2). И обязан быть выводимым: разрешить один и тот же конфликт поверх
     * одной и той же серверной версии дважды (два нажатия, переигранная транзакция) — это одно
     * намерение, и второй ключ развёл бы его на две операции.
     *
     * Версия, которой сервер не назвал, кодируется словом, а не пустотой: пустая часть склеила бы
     * ключ разрешения с ключом следующего разрешения поверх версии 0.
     */
    fun resolutionKey(
        mutationId: String,
        serverVersion: Long?,
    ): String {
        require(mutationId.isNotBlank()) { "mutationId must not be blank" }
        return mutationId + "-r" + (serverVersion?.toString() ?: "none")
    }
}
