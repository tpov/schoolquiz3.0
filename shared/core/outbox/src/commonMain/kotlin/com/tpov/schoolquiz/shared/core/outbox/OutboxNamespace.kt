package com.tpov.schoolquiz.shared.core.outbox

/**
 * Пространство имён владеющей фичи — половина NFR4 про `entity_ref`.
 *
 * `operation` и `entity_ref` пишутся как `<фича>.<имя>` и принадлежат одной и той же фиче: по
 * `operation` ядро находит обработчик, по `entity_ref` фича находит свою строку. Разъедутся — и
 * пометка «не отправлено» встанет на чужую сущность либо не встанет ни на какую, а заметить это
 * будет некому: ядро в [OutboxRecord.payload] не смотрит (AD-7) и подмену не увидит.
 *
 * Ссылка при этом на части не разбирается. Ядро берёт от обеих строк ровно то, что объявлено
 * общим, — имя фичи до первого разделителя — и сравнивает эти два имени целиком. Что стоит
 * дальше (`RESULT:42`, `draft:draft-1`), остаётся делом самой фичи.
 */
object OutboxNamespace {
    /**
     * Разделители, за которыми кончается имя фичи.
     *
     * Их два, потому что в дереве живут обе формы: `quest.QUEST:7` и `lesson_runner:attempt:a1`.
     * Приводить их к одной — отдельная работа с миграцией уже лежащих строк, а правило про
     * совпадение имён нужно раньше неё.
     */
    private const val SEPARATORS = ".:"

    /** Имя фичи, которой принадлежит имя операции или ссылка на сущность. */
    fun of(name: String): String {
        val cut = name.indexOfFirst { it in SEPARATORS }
        return if (cut < 0) name else name.substring(0, cut)
    }

    /**
     * Отвергает запись, чья ссылка живёт не в том пространстве имён, что её операция.
     *
     * Зовётся при постановке в очередь: до вставки, чтобы отвергнутая запись не оставила строки в
     * таблице. Место вызова — общая форма строки очереди (строка таблицы в слое хранения), а не
     * хранилище: хранилище лишь один путь постановки, а владеющие фичи кладут строку своей
     * транзакцией вместе с локальным изменением (AD-23) и мимо хранилища проходят.
     *
     * Запись без ссылки законна — пометки на сущности у неё просто нет.
     */
    fun requireSameNamespace(
        operation: String,
        entityRef: String?,
    ) {
        if (entityRef == null) return
        val ofOperation = of(operation)
        val ofEntityRef = of(entityRef)
        require(ofOperation == ofEntityRef) {
            "entity_ref \"$entityRef\" живёт в пространстве имён \"$ofEntityRef\", " +
                "а operation \"$operation\" — в \"$ofOperation\" (NFR4)"
        }
    }
}
