package com.tpov.schoolquiz.shared.core.outbox

/**
 * Квитанция-маркер реплея арена-settle — первый класс, а не случайный побочный продукт.
 *
 * Сервер отвечает отказом `SETTLEMENT_REUSE` (already-exists), когда попытка с этим attemptId
 * уже зафиксирована сохранённым settlement'ом, а тело повторного запроса расходится с тем,
 * что было зафиксировано: другой отпечаток, другой владелец. Попытка терминальна на сервере —
 * повторять её бессмысленно, карантинить нечего (эффект уже там), а выдумывать второй эффект
 * запрещено (AD-1). Поэтому движок ACK-ает такую строку очереди, оставляя вместо серверной
 * квитанции этот маркер: он объясняет, почему квитанции с оценками нет.
 *
 * Парсинг маркера — дело владеющей фичи: `AttemptSettlementReceiptParser` читает константу
 * нарочно и поднимает из неё `LEGACY_RECORDED` (засчитано без доказательства оценки, никогда
 * не ноль, повтору не подлежит). Строка здесь, а не собранная по месту: маркер живёт в базе
 * квитанций дольше самой записи очереди, и обе стороны — писатель и читатель — обязаны
 * называть его одним и тем же литералом.
 */
object SettlementReplayReceipt {
    /** Ровно то, что движок кладёт в `payloadJson` ACK-нутой строки реплея settle. */
    const val PAYLOAD_JSON: String = "{\"settlementAlreadyRecorded\":true}"
}
