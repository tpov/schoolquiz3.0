package com.tpov.schoolquiz.shared.core.outbox

/**
 * Что очередь знает про одну сущность — закрытый набор из двух ответов.
 *
 * Ответ «неотправленного нет» здесь такое же значение, как и всякое другое, а не `null`. Пока он
 * был пустотой, «по этой ссылке ничего не ждёт» было неотличимо от «ещё не спрашивали» и от
 * «поток пока молчит»: три разных положения дел приезжали в фичу одной и той же пустотой, и
 * каждая решала за себя, что она значит. Пометку сущности (AD-14) на таком ответе не построить.
 *
 * Ссылка на сущность для ядра непрозрачна: строку составила и разбирает та фича, которая запись
 * создала (AD-7). Ядро сравнивает её целиком и в части не заглядывает.
 */
sealed interface OutboxEntitySync {
    /** По этой ссылке отложенного нет — ни ждущего, ни застрявшего. */
    data object None : OutboxEntitySync

    /**
     * По ссылке есть запись, и вот что с ней.
     *
     * Числа наружу отдаются целыми, а не строкой: экран черновика показывает «поверх версии 7», и
     * собирать это разбором [OutboxRecord.lastError] запрещено (AD-15).
     *
     * @property recordId запись, которой это состояние принадлежит, — по ней и разрешают конфликт.
     * @property state что с записью сейчас.
     * @property expectedVersion версия, с которой мутация уходила.
     * @property serverVersion версия, которую назвал сервер. Пусто, пока конфликта не было.
     */
    data class Queued(
        val recordId: Long,
        val state: OutboxState,
        val expectedVersion: Long? = null,
        val serverVersion: Long? = null,
    ) : OutboxEntitySync {
        /** Разошлась ли сущность с сервером — то единственное, что требует решения игрока (AD-24). */
        val isConflicted: Boolean get() = state == OutboxState.CONFLICT
    }
}
