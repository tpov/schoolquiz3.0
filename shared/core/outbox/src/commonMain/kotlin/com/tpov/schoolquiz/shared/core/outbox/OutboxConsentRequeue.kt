package com.tpov.schoolquiz.shared.core.outbox

/**
 * Возвращает в очередь записи, ждущие согласия игрока с платными условиями (CAP-16, AD-5).
 *
 * Отказ сервера `terms-consent-required` паркует платную запись в `CONFLICT` — она ждёт решения
 * игрока, как конфликт версий, но решает его согласие, а не новая версия. Момент решения один:
 * игрок согласился с текущими условиями (`acceptCurrentTerms`). Тогда же запись и возвращается —
 * под тем же ключом идемпотентности (согласие не входит в отпечаток запроса), уже с захваченным
 * снимком свежих условий.
 *
 * Фильтр по операциям — [OutboxOperations.termsConsentOperations], и он обязателен: общий
 * «вернуть все конфликтные» отправил бы заново и конфликт версий, чьё решение — новая мутация
 * поверх серверной версии (AD-24), а не повтор старой.
 *
 * Владельца вызов не сужает, хотя записи owner-scoped: согласие — не auth-scoped по контракту
 * (цены от того, кто вошёл, не зависят), и согласившийся аккаунт снимает ожидание записей всех
 * владельцев устройства. Изоляция владельца от этого не страдает: каждая запись по-прежнему
 * уезжает только под своим `owner_uid` (AD-8).
 */
interface OutboxConsentRequeue {
    /** Сколько записей вернулось в отправку. */
    suspend fun requeueConflictedTerms(): Int
}
