package com.tpov.schoolquiz.shared.core.network

/**
 * Почему обращение к серверу не удалось — в терминах, по которым можно принять решение.
 *
 * Сегодня отсутствие сети и «не хватает золота» доходят наверх одинаково: как текст в
 * `error.message`. Решать по строке нельзя, поэтому AD-15 вводит закрытый набор из пяти ветвей,
 * и каждая обязана сказать, что с ней делать дальше — [disposition] не имеет значения по
 * умолчанию, так что новую ветвь нельзя добавить, не приняв это решение.
 *
 * Тип живёт в общем коде и ничего не знает ни про Firebase, ни про Android: SDK-исключения
 * отображаются в него на границе, в `platform`.
 */
sealed interface SyncError {
    /** Что движок очереди должен сделать с записью, получившей эту ошибку. */
    val disposition: Disposition

    /**
     * Связи нет. Это не отказ: сервер вообще не услышал запрос, поэтому повторять безопасно.
     *
     * Синхронная мутация в этом состоянии не показывает спиннер, а сразу говорит словами, что
     * нужен интернет — сегодня она крутится до истечения таймаута.
     */
    data object NoNetwork : SyncError {
        override val disposition: Disposition get() = Disposition.RETRY
    }

    /**
     * Условие ещё не выполнено, но выполнится: мутация, от которой зависит эта, всё ещё летит
     * из той же очереди. Очередь не обещает порядок (AD-27), поэтому «разблокировал урок и
     * прошёл его» может приехать наоборот.
     *
     * Отличается от [Refused] ровно тем, что это «ещё нет», а не «нет».
     */
    data object PreconditionNotMet : SyncError {
        override val disposition: Disposition get() = Disposition.RETRY
    }

    /**
     * Сервер посмотрел и отказал: не хватает валюты, нет прав, предмет уже занят. Повтор ничего
     * не изменит, поэтому запись уходит в карантин, а не крутится по кругу.
     *
     * @property reason причина в том виде, в каком её назвал сервер — для показа и для журнала.
     */
    data class Refused(val reason: String) : SyncError {
        override val disposition: Disposition get() = Disposition.QUARANTINE
    }

    /**
     * Сущность изменилась под нами: версия, с которой мутация уходила, устарела. Не отказ и не
     * повод для карантина — по AD-24 клиент принимает серверную версию и поднимает решение наверх.
     *
     * @property serverVersion версия, которую назвал сервер. Пусто, пока сервер не научится её
     *   присылать — это работа эпика E8, до неё ветвь существует, но номера не несёт.
     */
    data class VersionConflict(val serverVersion: Long? = null) : SyncError {
        override val disposition: Disposition get() = Disposition.CONFLICT
    }

    /**
     * Ничего из перечисленного. Повторяем: неизвестное чаще оказывается временным, а вечный
     * повтор всё равно оборвётся по порогу отказов и по предельному возрасту записи (AD-22).
     *
     * @property throwable исходная причина, если она была — для журнала, не для показа игроку.
     */
    data class Unknown(val throwable: Throwable? = null) : SyncError {
        override val disposition: Disposition get() = Disposition.RETRY
    }

    /** Что делать с записью очереди, получившей ошибку. Правило целиком задано AD-15. */
    enum class Disposition {
        /** Отложить и попробовать снова. */
        RETRY,

        /** Повторять бессмысленно — в карантин, последствие разбирает владеющая фича (AD-28). */
        QUARANTINE,

        /** Ждёт решения: клиент принимает серверную версию и спрашивает игрока (AD-24). */
        CONFLICT,
    }
}

/** Повторять ли обращение. Короткая форма самой частой проверки над [SyncError.disposition]. */
val SyncError.isRetryable: Boolean
    get() = disposition == SyncError.Disposition.RETRY
