package com.tpov.schoolquiz.shared.core.network

import kotlinx.coroutines.flow.Flow

/**
 * Есть ли сейчас связь.
 *
 * Приложение до сих пор этого не знало: детектора сети в проекте нет ни одного, поэтому
 * «нет интернета» и «сервер отказал» доходили до экрана неразличимыми. Контракт живёт в общем
 * коде, реализация — в `platform`, потому что знание о связи платформенное.
 *
 * Ответ всегда лишь настолько свеж, насколько успела обновиться система: связь может пропасть
 * между проверкой и запросом. Поэтому монитор — способ не начинать заведомо бессмысленное
 * обращение, а не замена обработке [SyncError.NoNetwork] после него.
 */
interface NetworkMonitor {
    /** Наблюдение за связью. Отдаёт текущее состояние сразу при подписке, дальше — изменения. */
    fun observeOnline(): Flow<Boolean>

    /** Состояние связи на этот момент — для одиночной проверки перед синхронным вызовом. */
    suspend fun isOnline(): Boolean
}
