package com.tpov.schoolquiz.shared.core.persistence

import com.tpov.schoolquiz.shared.core.outbox.OutboxState

/** Чем SQLite отвечает на вставку, подавленную `OnConflictStrategy.IGNORE`. */
const val OUTBOX_ROW_IGNORED: Long = -1L

/**
 * Проверяет, что подавленная вставка означает «это намерение уже в очереди», а не «оно не уедет».
 *
 * `IGNORE` возвращает −1 в двух случаях, и они противоположны по смыслу. Первый — обещание ключа
 * идемпотентности (AD-2): то же намерение уже отложено, вторая строка не нужна, всё в порядке.
 * Второй — под этим ключом лежит запись в карантине. Карантин терминален, и движок карантинную
 * строку не удаляет: она никуда не уедет и продолжит занимать ключ. Принять здесь −1 на веру
 * значит записать локальное изменение, показать его игроку сделанным и не отправить никогда —
 * ровно та молчаливая потеря, от которой транзакция «локальная половина вместе со своей строкой
 * очереди» и защищает (AD-23).
 *
 * Поэтому у ключа спрашивается состояние, и терминальное роняет транзакцию целиком: локальной
 * половины без своей записи очереди существовать не должно, а игрок получает отказ и может
 * повторить действие — уже новым намерением, с новым ключом.
 */
fun requireOutboxIntentQueued(
    insertResult: Long,
    mutationId: String,
    stateOfExistingRow: String?,
) {
    if (insertResult != OUTBOX_ROW_IGNORED) return

    val state = OutboxState.entries.firstOrNull { it.name == stateOfExistingRow }
    checkNotNull(state) {
        "Строку очереди $mutationId не приняли, а записи под этим ключом нет" +
            (stateOfExistingRow?.let { " (состояние '$it' неизвестно)" } ?: "")
    }
    check(!state.isTerminal) {
        "Ключ $mutationId занят записью в состоянии $state: она уже никуда не уедет, " +
            "и локальное изменение осталось бы навсегда расходиться с сервером"
    }
}
