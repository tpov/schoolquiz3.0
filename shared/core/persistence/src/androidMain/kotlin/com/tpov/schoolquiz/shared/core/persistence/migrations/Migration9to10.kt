package com.tpov.schoolquiz.shared.core.persistence.migrations

import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

/**
 * Разводит след прогона по расписаниям: ключ становится парой «владелец + вид прогона» (AD-14).
 *
 * До этой версии след был один на два расписания, разведённых эпиком 9 намеренно. Контентный
 * прогон и профильный писали в одну строку, и последний доложивший затирал соседа: удачный
 * профильный прогон снимал ветвь упавшего контентного и ставил поверх неё своё время успеха.
 * Игрок видел «синхронизировались минуту назад» над содержимым, которое не приезжало сутки, —
 * то самое молчание, ради устранения которого состояние и выводится наружу.
 *
 * **Прежние строки не переносятся.** У строки старой схемы вида нет и восстановить его нечем:
 * записать её контентной значило бы объявить содержимое свежим на основании прогона, который мог
 * быть профильным, — то есть повторить ровно ту ложь, которую эта миграция убирает. Приписать
 * обоим видам — та же ложь дважды. Пустая таблица здесь честна: «в этой версии ни одно расписание
 * ещё не отчитывалось» — ровно то, что приложение про устройство знает; первый же прогон каждого
 * вида напишет свою строку. Теряется при этом диагностический след, а не данные игрока: серверного
 * двойника у него нет, но и восстановить из него нечего.
 *
 * `PRIMARY KEY` в SQLite не меняется на месте — только пересозданием таблицы. Соседей миграция не
 * трогает: очередь, курсоры и локальные строки к следу отношения не имеют.
 */
val Migration9to10 =
    object : Migration(9, 10) {
        override fun migrate(db: SupportSQLiteDatabase) {
            db.execSQL("DROP TABLE IF EXISTS `sync_run_trace`")
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `sync_run_trace` (" +
                    "`owner_uid` TEXT NOT NULL, " +
                    "`kind` TEXT NOT NULL, " +
                    "`last_success_at_ms` INTEGER NOT NULL, " +
                    "`last_error_branch` TEXT, " +
                    "`last_error_reason` TEXT, " +
                    "`last_error_server_version` INTEGER, " +
                    "PRIMARY KEY(`owner_uid`, `kind`))",
            )
        }
    }
