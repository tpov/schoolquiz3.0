package com.tpov.schoolquiz.shared.feature.ads.domain

/**
 * Где вообще может жить реклама (CAP-7, история 3.4).
 *
 * Перечень закрытый и исчерпывающий: разблокировка коробки и экран предложений. Место, которого
 * здесь нет, рекламы не имеет — в том числе урока: «ни одной рекламной поверхности во время
 * урока» выражено тем, что урока в перечне нет, и сканом исходников, который это называет.
 */
enum class AdPlacement {
    /** Разблокировка коробки: пять подтверждённых сетью просмотров стоят одну коробку. */
    BOX_UNLOCK,

    /** Экран предложений: витрина аукциона (эпик 4) с одной рекламой на экране. */
    OFFERS_SCREEN,
}
