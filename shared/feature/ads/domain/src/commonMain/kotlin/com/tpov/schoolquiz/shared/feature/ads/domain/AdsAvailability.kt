package com.tpov.schoolquiz.shared.feature.ads.domain

/**
 * Ответ врат: реклама в этом месте включена или выключена.
 *
 * Оба состояния именованные: «выключено» — не отсутствие кода и не молчаливый ноль, а ответ,
 * который потребитель читает и называет игроку. Сборка без идентификатора AdMob отвечает
 * [Disabled] всюду и не падает.
 */
sealed interface AdsAvailability {
    /** Рекламы здесь нет: поверхности не рисуются, запросы не делаются. */
    data object Disabled : AdsAvailability

    /** Место разрешено: потребителю можно показывать рекламную поверхность. */
    data object Enabled : AdsAvailability
}
