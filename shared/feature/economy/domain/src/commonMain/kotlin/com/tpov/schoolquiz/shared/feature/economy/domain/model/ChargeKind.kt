package com.tpov.schoolquiz.shared.feature.economy.domain.model

/**
 * Два вида зарядов.
 *
 * Раньше это были сердца — обычное и золотое. Заряд отличается от сердца не названием: он тратится
 * не только за попытку, а по прейскуранту, и второй вид тратится вообще на другое.
 */
enum class ChargeKind {
    /**
     * Обычный, жёлтый.
     *
     * Платит за попытки по прейскуранту и за подсказку на лёгком вопросе. Покупается за нолики —
     * мотивационную валюту, — поэтому и тратить его можно офлайн, а сервер сверяет потом.
     */
    STANDARD,

    /**
     * Плазменный.
     *
     * Пропускает сложный вопрос, засчитывая его верным, — и потому никогда не показывает ответ:
     * показанный ответ на втором аккаунте стоил бы ровно ничего. За попытки не платит вовсе.
     * Покупается за золото, значит монетарный: тратится только на связи.
     */
    PLASMA,
}
