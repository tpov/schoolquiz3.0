package com.tpov.schoolquiz.shared.feature.economy.domain.repository

import com.tpov.schoolquiz.shared.feature.economy.domain.model.EconomyConstants
import kotlinx.coroutines.flow.Flow

/**
 * Настройки экономики, какими их видит устройство.
 *
 * Таблицей владеет сервер: коллекция `configs/` закрыта правилами, и клиент читает её только через
 * вызов, свёрнутый в обычную синхронизацию. Здесь — то, что уже приехало, плюс загрузочная копия
 * для устройства, которое ещё ни разу не синхронизировалось.
 *
 * Это **не** источник истины ни для чего, что решает сервер: цена покупки определяется той версией
 * таблицы, которая действовала в момент, когда сервер её принял, а не той, по которой клиент
 * нарисовал витрину.
 */
interface EconomyConstantsRepository {

    /** Текущая таблица. До первой удачной синхронизации — загрузочная копия. */
    fun observe(): Flow<EconomyConstants>

    /**
     * Спрашивает сервер и сохраняет ответ.
     *
     * Сервер знает, какая версия у устройства, и на совпадении не присылает ничего: таблица
     * меняется редко, а синхронизация идёт часто.
     */
    suspend fun refresh(): Result<Unit>
}
