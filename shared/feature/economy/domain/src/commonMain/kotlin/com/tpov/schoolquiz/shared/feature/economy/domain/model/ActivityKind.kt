package com.tpov.schoolquiz.shared.feature.economy.domain.model

/**
 * За что берётся плата обычными зарядами.
 *
 * Вид решает **сервер**, а не устройство: сегодня событие результата несёт `sourceShelf`, который
 * отличает турнир от домашнего квеста, но ценой никогда не был. Если вид называет клиент, а сервер
 * по названному списывает, то самый дешёвый вид — это тот, который назовёт любой клиент.
 */
enum class ActivityKind {
    /** Обычный урок. */
    ORDINARY_LESSON,

    /** Арена — разбор чужого черновика. */
    ARENA,

    /** Контрольная по теме. */
    THEME_TEST,

    /** Итоговый экзамен. */
    FINAL_EXAM,

    /** Турнир. */
    TOURNAMENT,
}
