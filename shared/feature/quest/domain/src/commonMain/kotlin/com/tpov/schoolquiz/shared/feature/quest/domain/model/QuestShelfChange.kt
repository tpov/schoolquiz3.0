package com.tpov.schoolquiz.shared.feature.quest.domain.model

/**
 * Намерение разработчика перенести публичный квест на другую полку.
 *
 * Полка — серверно-защищённое поле (AD-25): локально она не меняется ни при каких условиях. Поэтому
 * здесь нет ни прежней полки, ни новой строки квеста — только то, что уедет на сервер: чей квест,
 * какой и куда. Новая полка приедет журналом изменений, когда сервер её применит.
 *
 * @property id ключ намерения. Рождается вместе с нажатием и не меняется ни при одной попытке
 *   (AD-2). Один и тот же квест можно переносить сколько угодно раз, и каждый перенос — своё
 *   намерение со своим ключом: выведи ключ из `questId`, и второй перенос лёг бы под ключ первого,
 *   а сервер вернул бы на него сохранённый ответ, ничего не применив.
 * @property ownerUid чей аккаунт. Запись очереди не отправляется под другим (AD-8).
 * @property questId какой квест.
 * @property targetShelf куда. Только из [Quest.VALID_SHELVES] — те же пять значений держит сервер.
 */
data class QuestShelfChange(
    val id: String,
    val ownerUid: String,
    val questId: QuestId,
    val targetShelf: String,
) {
    init {
        require(id.isNotBlank()) { "QuestShelfChange.id must not be blank" }
        require(ownerUid.isNotBlank()) { "QuestShelfChange.ownerUid must not be blank" }
        require(targetShelf in Quest.VALID_SHELVES) {
            "Unsupported targetShelf: $targetShelf. Allowed: ${Quest.VALID_SHELVES}"
        }
    }
}

/**
 * Что очередь знает о переносе этого квеста — закрытый набор, а не `Boolean` (история 4.4).
 *
 * Конфликта здесь быть не может: перенос не версионируется, и сервер отвергает его либо
 * окончательно, либо просит подождать. «Ещё нет» и «ждёт» для карточки одно и то же — ожидание.
 */
enum class QuestShelfSyncState {
    /** Неотправленного нет: либо не переносили, либо перенос уже доехал и запись удалена (AD-4). */
    NONE,

    /** Перенос лежит в очереди и уедет сам. */
    PENDING,

    /**
     * Сервер отверг перенос насовсем, запись больше не уедет (AD-28). Откатывать нечего — полка
     * локально не менялась (AD-25); последствие карантина здесь — эта пометка на карточке.
     */
    QUARANTINED,
}
