package com.tpov.schoolquiz.shared.feature.app_shell.domain.repository

/**
 * Сколько мягкой валюты списано локально, но ещё не доехало до сервера.
 *
 * Профильная синхронизация переписывает баланс снимком сервера, а сервер про такую трату ещё не
 * знает: у профиля своё расписание, и оно не ждёт прогона очереди. Без этой поправки уже
 * потраченные нолики возвращались бы игроку на экран, тратились второй раз, а откат карантина
 * добавлял бы возврат к уже восстановленному балансу — двойная трата и двойной возврат сразу.
 *
 * Порт объявлен здесь, а реализован владеющей фичей: ядро в тело записи очереди не смотрит (AD-7),
 * а профиль не знает, какие фичи что покупают. Собирает пару композиционный корень.
 */
fun interface PendingLocalCharges {
    /**
     * Сумма списаний, чьи записи очереди ещё не доставлены.
     *
     * Ноль — когда доставлено всё: тогда снимок сервера уже включает трату, и вычитать нечего.
     * Число самовосстанавливается: запись уехала — слагаемое исчезло.
     */
    suspend fun undeliveredNolics(ownerUid: String): Long
}
