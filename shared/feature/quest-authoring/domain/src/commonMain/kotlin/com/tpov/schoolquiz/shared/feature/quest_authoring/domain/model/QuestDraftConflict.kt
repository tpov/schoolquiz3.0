package com.tpov.schoolquiz.shared.feature.quest_authoring.domain.model

/**
 * Черновик разошёлся с сервером: заявка ушла с одной версией, а квест на сервере уже другой.
 *
 * Это не отказ и не карантин (AD-24). Работа автора цела, лежит в очереди и ждёт одного решения:
 * отправить её заново поверх той версии, которая на сервере сейчас.
 *
 * @property draftId чей черновик.
 * @property serverVersion версия, названная сервером. Пусто — сервер конфликт назвал, а версию не
 *   прислал: решать автору нечего, отправка заново ушла бы без сверки. Такое расхождение снимает
 *   следующий снимок с сервера, и попытка решить его отвергается.
 * @property expectedVersion версия, с которой заявка уходила. Показывает, откуда взялось
 *   расхождение, и в решении не участвует.
 */
data class QuestDraftConflict(
    val draftId: QuestDraftId,
    val serverVersion: Long?,
    val expectedVersion: Long?,
)
