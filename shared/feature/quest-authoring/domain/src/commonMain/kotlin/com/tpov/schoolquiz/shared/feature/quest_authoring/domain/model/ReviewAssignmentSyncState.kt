package com.tpov.schoolquiz.shared.feature.quest_authoring.domain.model

/**
 * Что очередь знает про решение по заданию (AD-14).
 *
 * Закрытый набор, а не `Boolean`: карточке важно отличать «ещё уедет» от «не уедет никогда».
 * Карантин здесь — единственное последствие для задания: откатывать нечего (AD-25), сервер уже
 * ответил окончательно — задание переназначено или закрыто, — и пометка говорит об этом ревьюеру
 * вместо молчания (AD-28).
 */
enum class ReviewAssignmentSyncState {
    /** В очереди по этому заданию ничего нет. */
    NONE,

    /** Решение лежит в очереди и уедет само. */
    PENDING,

    /** Решение отвергнуто окончательно: сервер его не принял, и повтора не будет. */
    QUARANTINED,
}
