package com.tpov.schoolquiz.shared.feature.quest_authoring.data

/*
 * Что делать с приватным квестом, приехавшим с сервера, когда локальный черновик уже есть.
 *
 * Решение вынесено отдельно и сделано чистым намеренно: оно и есть то место, где Эпик 8 меняет
 * смысл слова «расхождение», а проверить смену смысла на трёх числах дешевле и честнее, чем через
 * базу.
 */

/**
 * Статусы, означающие «локально есть работа, которой на сервере ещё нет».
 *
 * Живут рядом с решением, а не внутри источника данных: правило без них не читается.
 */
val LOCAL_DIRTY_STATUSES: Set<String> =
    setOf(
        "DRAFT",
        "SAVED",
        "SYNC_PENDING",
        AWAITING_REVIEW_STATUS,
    )

/** Заявка отправлена и ждёт рецензии: единственный грязный статус, в котором версия — своя. */
const val AWAITING_REVIEW_STATUS: String = "REVIEW_QUEUED"

enum class PrivateQuestMerge {
    /** Локального черновика нет или он не грязный: снимок ложится как есть. */
    SAVE,

    /** Сервер ушёл вперёд той версии, на которой автор остановился, — расхождение (AD-24). */
    CONFLICT,

    /**
     * Сервер не сдвинулся, а локально есть несохранённая работа: приехало то же, что автор уже
     * видел. Перезаписывать нечем — снимок беднее того, что лежит.
     */
    KEEP_LOCAL,

    /**
     * Приехало эхо собственной заявки: черновик ждёт рецензии, и сервер только что назначил ему
     * версию. Содержимое остаётся своё, а версия записывается — иначе черновик её не узнаёт
     * никогда, следующая заявка уходит без номера, и сервер отвечает конфликтом на пустом месте.
     *
     * Только для `REVIEW_QUEUED`. Черновик с несданными правками версию не перенимает: та могла
     * прийти с другого устройства, и переняв её, следующая заявка прошла бы сверку и затёрла чужую
     * публикацию молча. Без номера она вместо этого получит от сервера конфликт — с номером, —
     * и его можно разрешить честно.
     */
    ADOPT_SERVER_REVISION,
}

/**
 * Расходится ли черновик с сервером.
 *
 * Меряется серверными версиями, и только ими (AD-12): конфликт — это когда квест на сервере уехал
 * дальше версии, которую автор знал. Прежнее правило сравнивало счётчик локальных правок с
 * серверной версией и потому объявляло расхождение за сам факт работы — десять сохранений
 * черновика давали «одиннадцать против четырёх», хотя на сервере никто ничего не менял.
 *
 * @param localStatus статус локального черновика; `null` — черновика нет.
 * @param knownServerRevision версия, на которой автор остановился. `null` — квест ещё не
 *   публиковался, сверять не с чем.
 * @param incomingServerRevision версия, назначенная сервером в приехавшем снимке. `null` — сервер
 *   версии ещё не назначал: сравнивать нечего, и объявлять расхождение не с чем. Раньше на это
 *   место подставлялось местное число, и «расхождение» получалось из сравнения клиента с собой.
 */
fun privateQuestMerge(
    localStatus: String?,
    knownServerRevision: Long?,
    incomingServerRevision: Long?,
    dirtyStatuses: Set<String> = LOCAL_DIRTY_STATUSES,
): PrivateQuestMerge {
    if (localStatus == null || localStatus !in dirtyStatuses) return PrivateQuestMerge.SAVE
    if (localStatus == AWAITING_REVIEW_STATUS && incomingServerRevision != null) {
        return PrivateQuestMerge.ADOPT_SERVER_REVISION
    }
    if (knownServerRevision != null && incomingServerRevision != null &&
        incomingServerRevision > knownServerRevision
    ) {
        return PrivateQuestMerge.CONFLICT
    }
    return PrivateQuestMerge.KEEP_LOCAL
}
