package com.tpov.schoolquiz.shared.feature.lesson.domain.model

/**
 * Чем кончилось нажатие «разблокировать» — на устройстве, до всякой отправки.
 *
 * Владелец решил 2026-09-03: разблокировка без сети открывает урок сразу — «это не золотой
 * материал». Нолики мягкая валюта, и локальная половина для неё разрешена, поэтому у нажатия есть
 * исход прямо здесь, а не только «положили намерение».
 *
 * Отказ по балансу — отдельная ветвь, а не общая неудача: он обязан называть свою причину, а не
 * выдавать себя за отсутствие связи (история 5.3).
 */
sealed interface LessonUnlockOutcome {
    /** Нолики списаны, урок открыт, намерение лежит в очереди — всё одной транзакцией (AD-23). */
    data object Opened : LessonUnlockOutcome

    /** Урок уже открыт: ни второго списания, ни второй записи в очереди (AD-2). */
    data object AlreadyOpen : LessonUnlockOutcome

    /**
     * Локальных ноликов не хватает. Записи в очереди нет: отправлять нечего, и повторять нечего.
     *
     * @param priceNolics цена, посчитанная той же функцией, что считает её сервер (история 5.2).
     * @param balanceNolics сколько у игрока есть сейчас.
     */
    data class NotEnoughNolics(
        val priceNolics: Int,
        val balanceNolics: Long,
    ) : LessonUnlockOutcome

    /** Профиля этого аккаунта на устройстве ещё нет: списывать не с чего. */
    data object NoProfile : LessonUnlockOutcome
}
