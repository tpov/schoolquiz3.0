package com.tpov.schoolquiz.shared.feature.lesson.domain.repository

import com.tpov.schoolquiz.shared.feature.lesson.domain.model.LessonId
import com.tpov.schoolquiz.shared.feature.lesson.domain.model.LessonUnlockOutcome
import kotlinx.coroutines.flow.Flow

/**
 * Разблокировка урока: локальная половина и намерение в общей очереди — одним действием.
 *
 * Порт объявлен фичей lesson, потому что ей же принадлежит имя операции `lesson.UNLOCK` и
 * пространство имён ссылки `lesson.LESSON:<id>` (NFR4). Прямой вызов callable, живший в economy,
 * снят: без сети он отвечал отказом, а не откладывал действие (AD-3, история 5.3).
 *
 * Вид покупки едет строкой, а не типом economy: домен lesson о типах чужой фичи не знает, а
 * приёмник читает из тела ровно эту строку (`kind`). Проверять её — дело того, кто зовёт.
 */
interface LessonUnlockQueue {
    /**
     * Списывает нолики, открывает урок и кладёт намерение — одной транзакцией (AD-23).
     *
     * Урок открывается сразу, ещё до отправки: владелец решил 2026-09-03, что нолики — мягкая
     * валюта и AD-25 на них не распространяется. Разойтись локальному и серверному состоянию не
     * даёт карантин: он откатывает обе половины (AD-28).
     *
     * Повторное намерение по тому же уроку и виду покупки — то же намерение: ключ выводится из
     * тройки «владелец, вид, урок», и вторая постановка второй записи не создаёт (AD-2).
     *
     * @param priceNolics цена, посчитанная той же функцией, что считает её сервер (история 5.2).
     * @return исход нажатия; [Result.failure] — только когда не удалась сама запись на диск.
     */
    suspend fun queueUnlock(
        ownerUid: String,
        lessonId: LessonId,
        kindWireName: String,
        priceNolics: Int,
    ): Result<LessonUnlockOutcome>

    /**
     * Уроки, чья покупка ушла в карантин и была откачена (AD-28).
     *
     * Источник — сама запись очереди, а не вторая таблица пометок: та разошлась бы с очередью.
     * Пометка живёт, пока живёт карантинная строка, и снимается вместе с ней — то есть переживает
     * закрытие экрана и перезапуск приложения, а не гаснет вместе с сообщением.
     */
    fun observeRefusedUnlocks(ownerUid: String): Flow<Set<LessonId>>
}
