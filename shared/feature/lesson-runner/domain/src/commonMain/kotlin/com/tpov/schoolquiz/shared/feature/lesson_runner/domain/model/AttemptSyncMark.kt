package com.tpov.schoolquiz.shared.feature.lesson_runner.domain.model

/**
 * Что очередь знает про одно прохождение — глазами экрана результата (AD-14).
 *
 * Закрытый набор, а не `Boolean`: «ещё не уехало» и «уже никогда не уедет» — разные новости, и
 * игроку они говорятся разными словами. Пустого значения нет: [NONE] — это ответ «ничего не
 * ждёт», а не «неизвестно».
 */
enum class AttemptSyncMark {
    /** Ничего не ждёт: запись уехала, её никогда не было или аккаунт сменился. */
    NONE,

    /** Ждёт отправки: прохождение сохранено локально и до сервера ещё не доехало. */
    NOT_SENT,

    /** Карантин: повторять бессмысленно, последствие разбирает фича (AD-28). */
    QUARANTINED,
}
