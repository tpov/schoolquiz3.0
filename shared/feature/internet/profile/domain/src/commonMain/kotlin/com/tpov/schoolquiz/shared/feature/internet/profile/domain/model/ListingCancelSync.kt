package com.tpov.schoolquiz.shared.feature.internet.profile.domain.model

/**
 * Что очередь знает про снятие лота с продажи (AD-14).
 *
 * Снятие не зовёт сервер напрямую: намерение ложится в очередь, а лот исчезает из витрины, когда
 * его удалит сервер. Пока запись лежит, строка лота показывает [QUEUED]; если сервер отказал
 * окончательно — лот успели купить, пока запись ждала, — запись в карантине, и строка показывает
 * [REFUSED]. Ничего локально не откатывается: локальной половины у снятия нет (AD-25).
 *
 * `null` там, где это читают, значит «очередь про этот лот ничего не знает».
 */
enum class ListingCancelSync {
    /** Снятие ждёт отправки или повторяется. */
    QUEUED,

    /** Сервер отказал насовсем: лота у продавца больше нет. */
    REFUSED,
}
