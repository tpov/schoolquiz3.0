// C1 / Theme 4 (Complex argumentation) / Lesson 3 — Conceding and rebutting
// Focus: the concede-then-counter move in technical debate and design review —
// granting a valid point and then pushing back without contradicting yourself.
// The pattern is a two-step structure: a CONCESSION marker ("admittedly...",
// "granted, X is true", "while I accept that...", "that is a fair point") that
// acknowledges merit, immediately followed by a REBUTTAL pivot ("but...", "even
// so", "nevertheless", "I would still argue", "that said") that reasserts the
// author's position. The DISCRIMINATOR throughout is the connector's logical
// role: a concessive opener must be paired with an adversative pivot, never with
// an additive ("moreover"), causal ("therefore"), or exemplifying ("for
// instance") link — only the connector that genuinely flips the direction of the
// argument is correct, and a bare concession with no rebuttal is incomplete.
// Sophisticated written register; real RFC / code-review / architecture-debate
// context, level C1. 40 questions, 20 EASY + 20 HARD, ordered 5x sc EASY,
// 5x sc HARD, 5x mc EASY, 5x mc HARD, 5x ord EASY, 5x ord HARD, 5x fb EASY,
