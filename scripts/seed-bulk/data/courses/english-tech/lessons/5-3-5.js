// B2 / Theme 3 (Professional communication) / Lesson 5 — Writing constructive feedback
// Focus: giving code-review and peer feedback that is specific, actionable and kind.
// Core moves: soften suggestions ("I'd suggest...", "you might want to...",
// "have you considered...?"); name what works ("one thing that works well is...");
// frame improvements without blame ("one thing to improve is...", "this is clear,
// and it would be even better if..."); separate the work from the person (critique
// the code, not the author); be specific (point at the exact line / function, not
// "this is bad"). Upper-intermediate register, pull-request / review-comment context.
// Discriminator throughout: politeness + specificity + criticising the WORK, not
// the developer. Plain "you're wrong / this is terrible / why did you do this" is
// the wrong register; vague praise or vague blame is unhelpful.
