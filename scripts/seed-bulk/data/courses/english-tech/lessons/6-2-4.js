// Focus: reasoning precisely about an API contract as it evolves — backward compatibility,
// the schema, breaking changes, semantic versioning (semver) and deprecation. The recurring
// discriminator is the exact meaning of a tight cluster of terms, each engineered to be
// uniquely correct:
//   schema              — the formal, declared shape of the request/response data;
//   contract            — the full promise an API makes to its clients (schema + behaviour + guarantees);
//   backward-compatible — existing clients keep working unchanged against the new version;
//   breaking change     — alters the contract so that some existing clients stop working;
//   deprecation         — flagging a still-working feature as discouraged and slated for removal.
// Semver facts are exact: MAJOR = incompatible/breaking, MINOR = backward-compatible additions,
// PATCH = backward-compatible fixes. Advanced, precise written register; design-doc / RFC context.
