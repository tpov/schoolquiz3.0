// B2 / Theme 4 (Argumentation) / Lesson 3 — Justifying a decision
// Focus: the language of justifying a technical decision and backing it with
// evidence — "we chose X because...", "the rationale is...", "the main reason
// is...", "this is justified by...", "the data shows...", "the trade-off is...",
// "given that...", "in light of...". Upper-intermediate register, ADR /
// design-review / RFC context. Usage notes: rationale = the reasoning behind a
// choice (a noun, "the rationale for X is Y"); justify / justified by = support
// with evidence or argument; "the main / primary reason" introduces the single
// strongest factor; "the data shows / the benchmark shows" cites measured
// evidence rather than opinion; trade-off = what you give up to gain something
// else; "given that ... / in light of ..." frame a decision against a
// constraint; a justification states WHY, an alternative names what you did NOT
// pick, and a constraint is the limit you decided within.
