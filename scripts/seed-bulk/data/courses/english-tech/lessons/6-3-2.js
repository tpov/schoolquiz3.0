// C1 / Theme 3 (Leadership communication) / Lesson 2 — Mentoring through code review
// Focus: the written register that turns a review comment into teaching rather than a verdict.
// A mentor explains the *rationale* behind a change, not only the change itself; frames a
// suggestion as "instead of X, consider Y because ...", surfaces "the principle here is ...",
// points forward with "as a next step you could ...", and asks *guiding questions* that let
// the author reach the conclusion themselves — a deliberate *learning moment*. The
// DISCRIMINATOR is register and intent, not grammar: nearly every distractor is itself
// grammatical and even technically correct, but reads as a bare *fix-it* directive (a verdict,
// a command, "just do X", "this is wrong") instead of mentoring that explains, invites
// reasoning and leaves agency with the author. Advanced, precise written register; pull-request
// and one-to-one mentoring context.
