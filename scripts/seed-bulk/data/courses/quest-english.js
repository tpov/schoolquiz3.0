// ---------------------------------------------------------------------------
// Wire question IDs based on lesson coordinates and question metadata.
// ---------------------------------------------------------------------------

function buildLesson(s, t, l, lessonId, lessonTitle, questions) {
  const TYPE_PREFIX = {
    SingleChoice: 'sc',
    MultipleChoice: 'mc',
    Ordering: 'ord',
    FillBlank: 'fb',
  };
  const DIFF_PREFIX = { EASY: 'e', HARD: 'h' };

  // Group by (type, difficulty) and assign 1..5 within each group preserving array order
  const counters = {};
  const wrapped = questions.map((q, order) => {
    const tPrefix = TYPE_PREFIX[q.type];
    const dPrefix = DIFF_PREFIX[q.difficulty];
    const key = `${tPrefix}-${dPrefix}`;
    counters[key] = (counters[key] || 0) + 1;
    const idx = counters[key];
    const id = `qsb-courses-english-${s}-${t}-${l}-${tPrefix}-${dPrefix}-${idx}`;
    return {
      id,
      order,
      text: q.text,
      payload: q,
    };
  });

  return {
    id: lessonId,
    title: lessonTitle,
    questions: wrapped,
  };
}

