// =====================================================================
// Helpers for compact question construction. Все вопросы — на русском.
// =====================================================================

function sc(qid, lessonPrefix, idx, diff, text, options, correctId, info) {
  const id = qid;
  return {
    id,
    text,
    payload: {
      type: 'SingleChoice',
      difficulty: diff,
      text,
      imageUrl: null,
      options,
      correctOptionId: correctId,
      info,
    },
  };
}

function mc(qid, lessonPrefix, idx, diff, text, options, correctIds, info) {
  return {
    id: qid,
    text,
    payload: {
      type: 'MultipleChoice',
      difficulty: diff,
      text,
      imageUrl: null,
      options,
      correctOptionIds: correctIds,
      info,
    },
  };
}

function ord(qid, lessonPrefix, idx, diff, text, items, info) {
  return {
    id: qid,
    text,
    payload: {
      type: 'Ordering',
      difficulty: diff,
      text,
      imageUrl: null,
      items,
      info,
    },
  };
}

function fb(qid, lessonPrefix, idx, diff, text, blanks, candidates, info) {
  return {
    id: qid,
    text,
    payload: {
      type: 'FillBlank',
      difficulty: diff,
      text,
      imageUrl: null,
      blanks,
      candidates,
      info,
    },
  };
}

// Helpers for option/item id-conventions
