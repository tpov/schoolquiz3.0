// =============================================================================
// Helpers
// =============================================================================

function questionId(s, t, l, type, diff, idx) {
  return `qsb-games-erudition-${s}-${t}-${l}-${type}-${diff}-${idx}`;
}

function sc(s, t, l, diff, idx, text, options, correctOptionId, info) {
  const id = questionId(s, t, l, 'sc', diff, idx);
  return {
    id,
    text,
    payload: {
      type: 'SingleChoice',
      difficulty: diff === 'e' ? 'EASY' : 'HARD',
      text,
      imageUrl: null,
      options,
      correctOptionId,
      info,
    },
  };
}

function mc(s, t, l, diff, idx, text, options, correctOptionIds, info) {
  const id = questionId(s, t, l, 'mc', diff, idx);
  return {
    id,
    text,
    payload: {
      type: 'MultipleChoice',
      difficulty: diff === 'e' ? 'EASY' : 'HARD',
      text,
      imageUrl: null,
      options,
      correctOptionIds,
      info,
    },
  };
}

function ord(s, t, l, diff, idx, text, items, info) {
  const id = questionId(s, t, l, 'ord', diff, idx);
  return {
    id,
    text,
    payload: {
      type: 'Ordering',
      difficulty: diff === 'e' ? 'EASY' : 'HARD',
      text,
      imageUrl: null,
      items,
      info,
    },
  };
}

function fb(s, t, l, diff, idx, text, blanks, candidates, info) {
  const id = questionId(s, t, l, 'fb', diff, idx);
  return {
    id,
    text,
    payload: {
      type: 'FillBlank',
      difficulty: diff === 'e' ? 'EASY' : 'HARD',
      text,
      imageUrl: null,
      blanks,
      candidates,
      info,
    },
  };
}

function opt(id, text) {
  return { id, text };
}

