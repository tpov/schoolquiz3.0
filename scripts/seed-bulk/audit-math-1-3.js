const val = s => {
  const raw = String(s).replace(/\s/g, '');
  let m;
  if (/^-?\d+\/-?\d+$/.test(raw)) { const [a, b] = raw.split('/').map(Number); return a / b; }
  if (/\(\d+\)/.test(raw)) {
    // периодическая дробь: [целая часть,][непериодическая часть](период)
    const sign = raw.trim().startsWith('-') ? -1 : 1;
    const mag = raw.replace(/^-/, '');
    const [intPart, fracPart] = mag.split(',');
    if (/\(\d+\)/.test(fracPart || '')) {
      const fm = fracPart.match(/^(\d*)\((\d+)\)/);
      const pre = fm[1] || '', p = fm[2];
      const pv = (Number(pre + p) - Number(pre || 0)) / Number('9'.repeat(p.length) + '0'.repeat(pre.length));
      return sign * (Number(intPart || 0) + pv);
    }
    return NaN;
  }
  if (/√/.test(raw)) { m = raw.match(/(\d*)√(\d+)/); const k = m && m[1] ? Number(m[1]) : 1; const sign = raw.trim().startsWith('-') ? -1 : 1; return sign * k * sqrt(Number(m[2])); }
  const n = parseFloat(raw.replace(/,/g, '.')); return isNaN(n) ? NaN : n;
};
